#include <nanobind/nanobind.h>
#include <nanobind/ndarray.h>
#include <nanobind/stl/string.h>

#include <cstddef>
#include <cstdint>
#include <stdexcept>
#include <string>
#include <utility>

#include "ndarray_helpers.h"
#include "ouster/core/typedefs.h"
#include "ouster/io/image_io.h"

namespace py = nanobind;
using ouster::sdk::core::rgb_img_t;
using ouster::sdk::io::GifWriter;
using ouster::sdk::python::ensure_c_contig;
using ImageMap = Eigen::TensorMap<const rgb_img_t<uint8_t>>;

// NOLINTNEXTLINE(misc-use-internal-linkage)
void init_io(py::module_& module, py::module_& /*unused*/) {
    module.doc() = R"(IO bindings generated by nanobind.

This module is generated from the C++ code and not meant to be used directly.
)";

    module.def(
        "read_png",
        [](const std::string& filename) {
            rgb_img_t<uint8_t> image;
            {
                py::gil_scoped_release release;
                image = ouster::sdk::io::read_png(filename);
            }
            auto* owned = new rgb_img_t<uint8_t>(std::move(image));
            py::capsule owner(
                owned, [](void* ptr) noexcept { delete static_cast<rgb_img_t<uint8_t>*>(ptr); });
            size_t shape[3] = {static_cast<size_t>(owned->dimension(0)),
                               static_cast<size_t>(owned->dimension(1)),
                               static_cast<size_t>(owned->dimension(2))};
            const size_t ndim = shape[2] == 1 ? 2 : 3;
            return py::ndarray<uint8_t, py::numpy, py::c_contig>(owned->data(), ndim, shape, owner);
        },
        py::arg("filename"),
        R"(
        Reads a PNG file into an 8 bit per channel image.

        Palette images are expanded to RGB, transparency to an alpha channel,
        and 16 bit images are scaled down to 8 bits. Gray images stay gray.

        Args:
            filename: the PNG file to read.

        Returns:
            A uint8 array of shape (H, W) for gray images, or (H, W, C) with C
            being 2 (gray, alpha), 3 (RGB) or 4 (RGBA).

        Raises:
            RuntimeError: if the file can't be read or isn't a valid PNG.
        )");

    module.def(
        "write_png",
        [](const std::string& filename, const py::ndarray<py::ro>& image) {
            auto pixels = ensure_c_contig<uint8_t>(image);
            if (pixels.ndim() != 2 && pixels.ndim() != 3) {
                throw std::invalid_argument("write_png: image must have shape (H, W) or (H, W, C)");
            }
            const ImageMap map(pixels.data(), static_cast<Eigen::Index>(pixels.shape(0)),
                               static_cast<Eigen::Index>(pixels.shape(1)),
                               pixels.ndim() == 2 ? 1 : static_cast<Eigen::Index>(pixels.shape(2)));
            py::gil_scoped_release release;
            ouster::sdk::io::write_png(filename, map);
        },
        py::arg("filename"), py::arg("image"),
        R"(
        Writes an 8 bit per channel image to a PNG file tagged as sRGB.

        Args:
            filename: the PNG file to write; overwritten if it exists.
            image: a uint8 array of shape (H, W) for gray, or (H, W, C) with C
                being 1 (gray), 2 (gray, alpha), 3 (RGB) or 4 (RGBA).

        Raises:
            TypeError: if the image isn't a uint8 array.
            ValueError: if the image shape is invalid.
            RuntimeError: if the file can't be written.
        )");

    py::class_<GifWriter>(module, "GifWriter", R"(
        Writes an animated GIF one frame at a time.

        Each frame is encoded when it's added, with its own palette, so only one
        frame is held in memory. The GIF loops forever. Can be used in a
        ``with`` block, which closes the writer on exit.
        )")
        .def(py::init<const std::string&, size_t, size_t>(), py::arg("filename"), py::arg("width"),
             py::arg("height"),
             R"(
            Opens a GIF file for writing.

            Args:
                filename: the GIF file to write; overwritten if it exists.
                width: width in pixels that every frame must have.
                height: height in pixels that every frame must have.

            Raises:
                ValueError: if the dimensions are invalid.
                RuntimeError: if the file can't be opened.
            )")
        .def(
            "add_frame",
            [](GifWriter& self, const py::ndarray<py::ro>& frame, double duration_ms) {
                auto pixels = ensure_c_contig<uint8_t>(frame);
                if (pixels.ndim() != 3) {
                    throw std::invalid_argument(
                        "GifWriter.add_frame: frame must have shape (H, W, 3) or (H, W, 4)");
                }
                const ImageMap map(pixels.data(), static_cast<Eigen::Index>(pixels.shape(0)),
                                   static_cast<Eigen::Index>(pixels.shape(1)),
                                   static_cast<Eigen::Index>(pixels.shape(2)));
                py::gil_scoped_release release;
                self.add_frame(map, duration_ms);
            },
            py::arg("frame"), py::arg("duration_ms"),
            R"(
            Encodes and appends a frame.

            GIF delays are stored in hundredths of a second. Rounding is carried
            over between frames so the total duration doesn't drift, and every
            frame is shown for at least 10 ms.

            Args:
                frame: a uint8 array of shape (height, width, 3) for RGB or
                    (height, width, 4) for RGBA; alpha is ignored.
                duration_ms: how long to show the frame, in milliseconds.

            Raises:
                TypeError: if the frame isn't a uint8 array.
                ValueError: if the frame shape doesn't match the writer.
                RuntimeError: if the writer is closed or encoding fails.
            )")
        .def("close", &GifWriter::close, py::call_guard<py::gil_scoped_release>(),
             R"(
            Writes the end of the file and closes it. Further calls do nothing.

            Raises:
                RuntimeError: if the file can't be written.
            )")
        .def_prop_ro("width", &GifWriter::width, "Frame width in pixels.")
        .def_prop_ro("height", &GifWriter::height, "Frame height in pixels.")
        .def(
            "__enter__", [](GifWriter* self) { return self; }, py::rv_policy::reference)
        .def(
            "__exit__",
            [](GifWriter& self, py::object& /*exc_type*/, py::object& /*exc_value*/,
               py::object& /*traceback*/) { self.close(); },
            py::arg("exc_type").none(), py::arg("exc_value").none(), py::arg("traceback").none());
}
